List<String> strokesFor(String char) {
  final List<String>? strokes = glyphStrokes[char];
  if (strokes != null && strokes.isNotEmpty) return strokes;
  return char.trim().isEmpty ? const <String>[] : fallbackGlyph;
}

/// True when the character has a hand-authored outline.
bool hasGlyph(String char) => glyphStrokes.containsKey(char);

/// How far [char] advances the pen, in units of the writing height.
double advanceFor(String char) => glyphAdvance[char] ?? defaultAdvance;

/// Whether [char] hangs below the baseline.
bool descendsFor(String char) => glyphDescender[char] ?? false;

/// Straight-line approximation of a glyph's width, used for scaling guesses.
///
/// Returns 1 for an empty or unknown glyph so callers never divide by zero.
double widthRatioFor(String char) {
  if (!hasGlyph(char)) return 1;
  double maxX = 0;
  for (final String stroke in glyphStrokes[char]!) {
    for (final String token in stroke.split(RegExp(r'[\s,]+'))) {
      if (token.isEmpty || token == 'M' || token == 'L' || token == 'Q' || token == 'C' || token == 'Z') {
        continue;
      }
      final double? x = double.tryParse(token);
      if (x != null && x > maxX) maxX = x;
    }
  }
  return math.max(maxX, 0.1);
}
