"""Content sanitisation + question-quality validation for examinations.

The AI-generation and legacy fallback pipelines occasionally leak internal
syllabus/retrieval metadata into candidate-facing question text (for example
"point 4", "topic 3", "learning objective 2", syllabus chunk ids). This module
strips that leakage and verifies each question matches its declared type before
anything reaches the PDF/DOCX renderers.

Public API
----------
- ``sanitize_text(text) -> str`` — remove internal identifiers/metadata tokens.
- ``sanitize_question(question: dict) -> dict`` — sanitise all candidate-facing
  fields of one question.
- ``question_problems(question: dict) -> list[str]`` — human-readable list of
  quality problems for a single question.
- ``validate_questions(questions: list[dict]) -> dict`` — report across a set.

The syllabus, learning objectives and source metadata remain available as hidden
fields (``learning_outcome``, ``reference`` and so on) so evidence/traceability
is preserved without leaking into the candidate paper.
"""

from __future__ import annotations

import re

# Internal metadata identifiers that must never appear in candidate-facing text.
# These only match *identifier-style* words/phrases, so legitimate subject
# terminology (e.g. "the point of a cell", "objective observation") is kept.
_LEAK_RE = re.compile(
    r"(?ix)"
    r'(^|\s|\(|")'
    r"(?:"
    r"(?:syllabus\s+(?:point|topic|objective|id|code|item)s?)\s*\d*"
    r"|(?:learning\s+(?:objective|outcome)\d*)\s*\d*"
    r"|(?:curriculum\s+objective\d*)\s*\d*"
    r"|(?:objective\s*\d+)"
    r"|(?:point\s*\d+)"
    r"|(?:topic\s*\d+)"
    r"|(?:subtopic\s*\d+)"
    r"|(?:item\s*\d+)"
    r"|(?:section\s*id|source\s*id|chunk\s*id|book\s*id)"
    r"|(?:topic_id|subtopic_id|book_id|source_id|syllabus_id|chunk_id)"
    r"|(?:retrieval|metadata|uuid)"
    r")"
    r'(\s|\)|"|\.|,|$)',
)

# Option/appendix filler phrases generated by weak fallbacks; dropped entirely.
_FILLER = re.compile(
    r"(?i)^\s*(?:the\s+)?opposite\s+of\b.*\.?\s*$"
    r"|^\s*(?:an?\s+)?unrelated\s+process\b.*\.?\s*$"
    r"|^\s*none\s+of\s+the\s+above\b.*\.?\s*$"
    r"|^\s*all\s+of\s+the\s+above\b.*\.?\s*$",
)


def sanitize_text(text: str) -> str:
    """Remove internal-identifier leakage from a candidate-facing string."""
    if not text:
        return ""

    def _replace(_m) -> str:
        # The matched span already includes leading/trailing whitespace/punctuation
        # boundaries; replace it with a single space so words never glue together.
        return " "

    cleaned = _LEAK_RE.sub(_replace, text)
    cleaned = re.sub(r"\s{2,}", " ", cleaned)
    # Drop whitespace glued to punctuation separators the regex keeps.
    cleaned = re.sub(r"\s+([,.?!;:])", r"\1", cleaned)
    return cleaned.strip()


def _sanitize_option(option: str) -> str:
    cleaned = sanitize_text(option).strip(" .")
    if _FILLER.search(cleaned):
        return ""
    return cleaned


def sanitize_question(question: dict) -> dict:
    """Return a copy of ``question`` with candidate-facing fields cleansed.

    Hidden metadata fields (correct_answer, learning_outcome, reference, rubric)
    are retained as-is for marking/traceability — they never leak because the
    candidate renderer does not print them.
    """
    cleaned = dict(question)
    cleaned["question_text"] = sanitize_text(str(question.get("question_text") or ""))
    options = []
    for o in question.get("options") or []:
        opt = _sanitize_option(str(o))
        if opt:
            options.append(opt)
    cleaned["options"] = options
    for sub in question.get("subquestions") or []:
        # handled in the constructed-paper build; keep sub-list intact here
        pass
    return cleaned


def question_problems(question: dict) -> list[str]:
    """Return a list of quality problems for ``question`` or an empty list."""
    problems: list[str] = []
    q_type = str(question.get("question_type") or "")
    text = str(question.get("question_text") or "")
    options = [str(o) for o in (question.get("options") or []) if str(o).strip()]
    marks = question.get("marks")

    # Internal-metadata leakage (the core defect).
    if _LEAK_RE.search(text) or any(_LEAK_RE.search(o) for o in options):
        problems.append("Contains internal identifiers (point/objective/topic ids).")
    # Word-spacing guard: no accidental concatenation.
    if _has_collapsed_words(text) or any(_has_collapsed_words(o) for o in options):
        problems.append("Words appear to be concatenated.")
    # MCQ must have a stem + 2-6 distinct plausible options.
    if q_type == "multiple_choice":
        if not text:
            problems.append("MCQ has no question stem.")
        if len(options) < 2:
            problems.append("MCQ must provide at least 2 options.")
        if len(set(o.strip().lower() for o in options)) != len(options):
            problems.append("MCQ contains duplicate options.")
        if any(_FILLER.search(o) for o in options):
            problems.append("MCQ uses generic filler options.")
    elif q_type in ("true_false",):
        if options and len(set(o.strip().lower() for o in options)) != 2:
            problems.append("True/false must have exactly two options.")
    # Every question needs text.
    if not text and not (q_type == "structured" and (question.get("subquestions"))):
        problems.append("Question has no text.")
    # Marks must be a positive integer.
    if marks is None:
        problems.append("Question has no marks.")
    else:
        try:
            if int(marks) < 1:
                problems.append("Question marks must be at least 1.")
        except (TypeError, ValueError):
            problems.append("Question marks are invalid.")
    return problems


_COLLAPSED = re.compile(r"[a-z0-9)][A-Z]")


def _has_collapsed_words(text: str) -> bool:
    """Heuristic for accidentally-concatenated words ("Whichofthe...").

    Return True when a token like "bestdescribes" (lowercase/uppercase run with
    no separator) is seen, which indicates the renderer/AI dropped spaces.
    """
    if not text:
        return False
    # A typical English word rarely glues two mid-word capitals together, so any
    # ``wordCharacterUppercase`` transition without a space is suspicious.
    return bool(_COLLAPSED.search(text))


def validate_questions(questions: list[dict]) -> dict:
    """Validate a full question set before rendering (spec §26).

    Returns ``{"clean": bool, "problems": {"<id>": [probs, ...]}, "total": n}``.
    """
    problems: dict[str, list[str]] = {}
    for q in questions:
        qid = str(q.get("id") or "?")
        issues = question_problems(q)
        if issues:
            problems[qid] = issues
    return {
        "clean": not problems,
        "problems": problems,
        "total": len(questions),
    }
