"""Controlled Asymptote templates for the diagram service.

Every template produces a complete ``.asy`` compilation unit from *validated*
values only (floats/ints/booleans formatted by ``_n`` and pre-sampled numeric
point lists). No caller-supplied text is ever interpolated into Asymptote code;
function expressions are sampled in Python against a whitelist and emitted as
coordinate lists, so the compiler never sees untrusted source.
"""

from __future__ import annotations

import math

_NUMBER_FMT = "%.6g"


def _n(value: float) -> str:
    """Format a number the way Asymptote's parser expects (never locale-based)."""
    return _NUMBER_FMT % float(value)


def _points(points: list[tuple[float, float]]) -> str:
    return "--".join("(%s,%s)" % (_n(x), _n(y)) for x, y in points)


_HEAD = """// generated by penrose diagrams service — do not edit
settings.outformat="svg";
settings.render=0;
"""


def right_triangle(a: float, b: float, unit: str = "") -> str:
    """Labelled right triangle with sides a, b and the computed hypotenuse."""
    c = math.hypot(a, b)
    ha, hb = a / 2.0, b / 2.0
    u = min(a, b) * 0.12
    suffix = (" " + unit) if unit else ""
    return (
        _HEAD
        + "size(340,250);\n"
        + "pair O=(0,0), A=(%s,0), B=(0,%s);\n" % (_n(a), _n(b))
        + "draw(O--A--B--cycle, blue+linewidth(1.5));\n"
        + "draw(O--(0,%s)--(%s,%s)--(%s,0)--cycle, black+linewidth(.9));\n"
        % (_n(u), _n(u), _n(u), _n(u))
        + "dot(O); dot(A); dot(B);\n"
        + 'label("$%s$", (0,%s), W);\n' % (_n(b), _n(hb))
        + 'label("$%s$", (%s,0), S);\n' % (_n(a), _n(ha))
        + 'label("$%s$", (%s,%s), NE);\n' % (_n(c), _n(ha), _n(hb))
        + 'label("$a=%s%s,\\ b=%s%s,\\ c=%s%s$", (%s,%s), 2.4*S);\n'
        % (_n(a), suffix, _n(b), suffix, _n(c), suffix, _n(ha), _n(hb))
        + 'label("right angle", O, 3*SW);\n'
    )


def circle_diagram(radius: float, show_axes: bool = True) -> str:
    """Circle with labelled radius on coordinate axes (coordinate geometry)."""
    r = radius
    out = _HEAD + "size(340,300);\n"
    out += "real r=%s;\n" % _n(r)
    if show_axes:
        out += "pair X=(r*1.55,0), Y=(0,r*1.55);\n"
        out += "draw(-X--X, black+linewidth(1), Arrow(7));\n"
        out += "draw(-Y--Y, black+linewidth(1), Arrow(7));\n"
        out += 'label("$x$", X, 0.8*E); label("$y$", Y, 0.8*N);\n'
        out += 'label("$%s$", (r,0), 2*S);\n' % _n(r)
        out += 'label("$%s$", (-r,0), 2*S);\n' % _n(-r)
        out += 'label("$%s$", (0,r), 2*W);\n' % _n(r)
    out += "draw(circle((0,0), r), blue+linewidth(1.6));\n"
    out += "draw((0,0)--r*dir(52), red+linewidth(1.3), Arrow(6));\n"
    out += 'dot("$O$", (0,0), SW);\n'
    out += 'label("$r=%s$", 0.5*r*dir(52), 0.9*NW);\n' % _n(r)
    return out


def function_plot(points: list[tuple[float, float]], xmin: float, xmax: float) -> str:
    """Plot of an already-sampled function y=f(x) as a coordinate polyline."""
    span = max(abs(xmin), abs(xmax), 1.0)
    ys = [p[1] for p in points] or [0.0]
    yabs = max(max(map(abs, ys)), 1.0)
    out = _HEAD + "size(420,300);\n"
    out += "real xs=%s, ys=%s;\n" % (_n(span * 1.15), _n(yabs * 1.25))
    out += "pair X=(xs,0), Y=(0,ys);\n"
    out += "draw(-X--X, black+linewidth(1), Arrow(7));\n"
    out += "draw(-Y--Y, black+linewidth(1), Arrow(7));\n"
    out += 'label("$x$", X, 0.8*E); label("$y$", Y, 0.8*N);\n'
    out += "dot((0,0));\n"
    out += "draw(%s, green+linewidth(1.7));\n" % _points(points)
    out += 'label("$x_0=%s$", (%s,0), 2*S);\n' % (_n(xmin), _n(xmin))
    out += 'label("$x_1=%s$", (%s,0), 2*S);\n' % (_n(xmax), _n(xmax))
    return out


def vectors(v1: tuple[float, float], v2: tuple[float, float] | None) -> str:
    """One or two labelled vectors from the origin (with optional construction)."""
    out = _HEAD + "size(360,300);\n"
    span = max(abs(v1[0]), abs(v1[1]), 1.0)
    if v2:
        span = max(span, abs(v2[0]), abs(v2[1]))
    span *= 1.4
    out += "pair X=(%s,0), Y=(0,%s);\n" % (_n(span), _n(span))
    out += "draw(-X--X, black+linewidth(.9), Arrow(6));\n"
    out += "draw(-Y--Y, black+linewidth(.9), Arrow(6));\n"
    out += "dot((0,0));\n"
    out += "draw((0,0)--(%s,%s), rgb(0,140,80)+linewidth(1.8), Arrow(8));\n" % (
        _n(v1[0]),
        _n(v1[1]),
    )
    out += 'label("$\\vec{u}$", (%s,%s), dir(%s));\n' % (
        _n(v1[0] / 2),
        _n(v1[1] / 2),
        _n(math.degrees(math.atan2(v1[1], v1[0])) + 90),
    )
    if v2:
        out += "draw((0,0)--(%s,%s), rgb(180,60,160)+linewidth(1.8), Arrow(8));\n" % (
            _n(v2[0]),
            _n(v2[1]),
        )
        out += 'label("$\\vec{v}$", (%s,%s), dir(%s));\n' % (
            _n(v2[0] / 2),
            _n(v2[1] / 2),
            _n(math.degrees(math.atan2(v2[1], v2[0])) - 90),
        )
        out += "draw((0,0)--(%s,%s), rgb(60,90,220)+linewidth(1.3)+dashed);\n" % (
            _n(v1[0] + v2[0]),
            _n(v1[1] + v2[1]),
        )
        out += 'label("$\\vec{u}+\\vec{v}$", (%s,%s), NE);\n' % (
            _n(v1[0] + v2[0]),
            _n(v1[1] + v2[1]),
        )
    return out


def energy_profile(dh_kj: float, exothermic: bool, title: str) -> str:
    """Energy-profile diagram; dh sign follows the reaction type exactly."""
    dh = float(dh_kj)
    rh = 0.0  # reactants level
    act = 2.6  # activation hump
    k = 0.011  # kJ -> drawing units
    final = rh + dh * k  # exothermic (dh<0) ends lower, endothermic higher
    colour = "rgb(210,110,30)" if exothermic else "rgb(40,90,190)"
    out = _HEAD + "size(460,320);\n"
    out += "pair R=(0,%s), P=(4.2,%s);\n" % (_n(rh), _n(final))
    out += "path curve=(0,%s)..(1.0,%s)..(1.9,%s)..(2.7,%s)..(4.2,%s);\n" % (
        _n(rh),
        _n(rh + act),
        _n((rh + act + final) / 2 + 0.6),
        _n(final + 0.35),
        _n(final),
    )
    out += "draw(curve, %s+linewidth(2));\n" % colour
    out += "draw((-0.3,%s)--(4.5,%s), grey+linewidth(.9)+dashed);\n" % (_n(rh), _n(rh))
    out += "draw((-0.3,%s)--(4.5,%s), grey+linewidth(.9)+dashed);\n" % (
        _n(final),
        _n(final),
    )
    # enthalpy arrow between the two levels
    ax = 3.6
    out += "draw((%s,%s)--(%s,%s), black+linewidth(1.4), Arrow(7));\n" % (
        _n(ax),
        _n(rh),
        _n(ax),
        _n(final),
    )
    out += 'label("$\\Delta H = %s%s$ kJ/mol", (%s,%s), 2*E);\n' % (
        ("+" if dh >= 0 else ""),
        _n(dh),
        _n(ax),
        _n((rh + final) / 2),
    )
    out += 'label("Reactants", (0.05,%s), 2*NW);\n' % _n(rh)
    out += 'label("Products", (4.15,%s), 2*NE);\n' % _n(final)
    out += 'label("Activated complex", (1.0,%s), N);\n' % _n(rh + act)
    out += 'label("Energy", (-0.35,%s+0.5), W);\n' % _n(rh + act)
    out += 'label("Reaction coordinate", (2.1,-0.75), S);\n'
    out += 'label("$%s$", (2.1,%s+0.15), N);\n' % (
        title.replace("$", ""),
        _n(rh + act + 1.0),
    )
    return out
