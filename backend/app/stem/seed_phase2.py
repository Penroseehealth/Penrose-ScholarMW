async def _seed_assessment_questions(db, concept_index: dict[str, int]) -> int:
    result = await db.execute(select(STMAssessmentQuestion).limit(1))
    if result.scalar_one_or_none():
        return 0
    # Build a reverse map: subject_slug -> first concept_id found (for fallback)
    slug_to_concept: dict[str, int] = {}
    for (_title, slug), cid in concept_index.items():
        if slug not in slug_to_concept:
            slug_to_concept[slug] = cid

    count = 0
    for q in ASSESSMENT_QUESTIONS:
        cid = await _find_concept_id(concept_index, q["concept_keyword"], "")
        if cid is None:
            # try to find any concept
            for v in concept_index.values():
                cid = v
                break
        if cid is None:
            continue
        db.add(
            STMAssessmentQuestion(
                concept_id=cid,
                question_text=q["question_text"],
                question_type=q["question_type"],
                options=q.get("options"),
                answer=q["answer"],
                explanation=q.get("explanation", ""),
                bloom_level=q["bloom_level"],
                difficulty=q["difficulty"],
                marks=q["marks"],
                assessment_type=q["assessment_type"],
            )
        )
        count += 1
    return count


