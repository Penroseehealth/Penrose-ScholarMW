async def _build_concept_index(db) -> dict[str, int]:
    """Return {concept_title: concept_id} with full hierarchy info for matching."""
    result = await db.execute(
        select(
            STEMConcept.id,
            STEMConcept.title,
            STEMSubtopic.title.label("subtopic_title"),
            STEMTopic.title.label("topic_title"),
            STEMDiscipline.title.label("discipline_title"),
            STEMSubject.subject_slug,
            STEMSubject.title.label("subject_title"),
        )
        .join(STEMSubtopic, STEMConcept.subtopic_id == STEMSubtopic.id)
        .join(STEMTopic, STEMSubtopic.topic_id == STEMTopic.id)
        .join(STEMDiscipline, STEMTopic.discipline_id == STEMDiscipline.id)
        .join(STEMSubject, STEMDiscipline.subject_id == STEMSubject.id)
    )
    return {(row.title, row.subject_slug): row.id for row in result.all()}


async def _find_concept_id(
    concept_index: dict[str, int],
    keyword: str,
    subject_slug: str,
) -> int | None:
    """Find the first concept ID whose title contains the keyword and matches the subject."""
    kw = keyword.lower()
    for (title, slug), cid in concept_index.items():
        if slug == subject_slug and kw in title.lower():
            return cid
    # fallback: any subject if slug not found
    for (title, _slug), cid in concept_index.items():
        if kw in title.lower():
            return cid
    return None


