"""Persistent models for the Interactive AI Presentation Engine.

Phase 1 of the authorized implementation (2026-11-06). These tables make
presentations and live sessions durable — the previous implementation kept
generated presentations in an in-process dict (presentation/service.py
``EngineStore``), which lost every deck on restart and could never support a
live session across the FastAPI and LiveKit-agent processes.

Design decisions (from the approved Phase 0D specification):

* Enum-valued columns are plain ``String`` fields with Python-side validation,
  matching the existing model style (``app/models/stem.py``) and staying
  portable across SQLite and PostgreSQL without sa.Enum migration hazards.
* Slide order uses a sparse ``position`` (step 1000) so a single-slide move is
  one UPDATE and never collides with a concurrent reorder.
* Event sequencing is transactional: ``(session_id, seq)`` is unique, and the
  sequence is assigned inside the same transaction as the event row (see
  ``app/presentation_session/events.py``, Phase 2).
* Consent history is append-only: withdrawal inserts a new row and never
  updates an existing one.
* The voice lease lives on the session row (atomic single-statement
  acquisition across processes — both FastAPI and the agent worker share the
  database as the only coordination channel).
"""

from __future__ import annotations

from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.engine import Base


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


# ---------------------------------------------------------------------------
# Persistent presentations (authoring)
# ---------------------------------------------------------------------------


class Presentation(Base):
    __tablename__ = "presentations"

    # UUID string generated by the presentation service — same id the
    # generation flow already used for its in-memory store.
    id: Mapped[str] = mapped_column(String(64), primary_key=True)
    owner_id: Mapped[int] = mapped_column(
        ForeignKey("users.id"), nullable=False, index=True
    )
    title: Mapped[str] = mapped_column(String(255), nullable=False, default="")
    config_json: Mapped[str | None] = mapped_column(Text, nullable=True)
    source_summary: Mapped[str | None] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, onupdate=_utcnow
    )

    slides: Mapped[list["PresentationSlide"]] = relationship(
        back_populates="presentation",
        cascade="all, delete-orphan",
        order_by="PresentationSlide.position",
    )


class PresentationSlide(Base):
    __tablename__ = "presentation_slides"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    presentation_id: Mapped[str] = mapped_column(
        ForeignKey("presentations.id", ondelete="CASCADE"), nullable=False
    )
    # Sparse ordering, step 1000: a single-slide move is one UPDATE; a batch
    # reorder writes disjoint sparse values inside one transaction. A
    # renormalization compacts positions when the gap decays (Phase 2).
    position: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    slide_id: Mapped[str] = mapped_column(String(64), nullable=False)
    slide_type: Mapped[str] = mapped_column(String(50), nullable=False, default="content")
    title: Mapped[str] = mapped_column(String(255), nullable=False, default="")
    bullets_json: Mapped[str | None] = mapped_column(Text, nullable=True)
    body: Mapped[str | None] = mapped_column(Text, nullable=True)
    speaker_notes: Mapped[str | None] = mapped_column(Text, nullable=True)
    citation: Mapped[str | None] = mapped_column(Text, nullable=True)
    layout: Mapped[str] = mapped_column(String(50), nullable=False, default="title_and_content")
    learning_objective: Mapped[str | None] = mapped_column(Text, nullable=True)

    presentation: Mapped["Presentation"] = relationship(back_populates="slides")

    __table_args__ = (
        Index("ix_presentation_slides_deck_pos", "presentation_id", "position"),
        UniqueConstraint(
            "presentation_id", "slide_id", name="uq_presentation_slide_ids"
        ),
    )


# ---------------------------------------------------------------------------
# Live sessions
# ---------------------------------------------------------------------------

# pres_state values (presentation lifecycle, presenter-controlled)
PRES_STATES = ("idle", "live", "paused", "completed")
# ai_state values (AI interaction, event-driven)
AI_STATES = ("idle", "listening", "awaiting_approval", "responding", "suspended")
AI_POLICIES = ("auto", "approval", "presenter_only")
VOICE_OWNERS = ("none", "agent", "client")
END_REASONS = ("presenter", "timeout", "presenter_absent")
PARTICIPANT_ROLES = ("presenter", "co_presenter", "attendee")


class PresentationSession(Base):
    __tablename__ = "presentation_sessions"

    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    presentation_id: Mapped[str] = mapped_column(
        ForeignKey("presentations.id"), nullable=False
    )
    presenter_id: Mapped[int] = mapped_column(
        ForeignKey("users.id"), nullable=False, index=True
    )
    # Server-generated; the only room name participants can join.
    room_name: Mapped[str] = mapped_column(String(80), nullable=False, unique=True)
    # Hashed join code for guest access (never stored in clear).
    join_code_hash: Mapped[str | None] = mapped_column(String(128), nullable=True)

    pres_state: Mapped[str] = mapped_column(String(20), nullable=False, default="idle")
    ai_state: Mapped[str] = mapped_column(String(20), nullable=False, default="idle")
    ai_policy: Mapped[str] = mapped_column(String(20), nullable=False, default="approval")

    # Voice arbitration (Phase 0D §5): one owner at a time, leased with expiry.
    voice_owner: Mapped[str] = mapped_column(String(10), nullable=False, default="none")
    voice_lease_token: Mapped[str | None] = mapped_column(String(36), nullable=True)
    voice_lease_expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    voice_next_allowed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    # Recovery (Phase 0D §8): presenter heartbeat; loss pauses instead of
    # ending; reconnect window decides the eventual presenter_absent end.
    presenter_heartbeat_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    presenter_lost_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    grace_period_s: Mapped[int] = mapped_column(Integer, nullable=False, default=180)
    reconnect_window_s: Mapped[int] = mapped_column(Integer, nullable=False, default=3600)

    # Recording (Phase 6, v1): presenter-side capture only; the artifact is a
    # row in the existing system-audio recordings storage.
    recording_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    recording_recording_id: Mapped[str | None] = mapped_column(String(64), nullable=True)

    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    ended_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    end_reason: Mapped[str | None] = mapped_column(String(20), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow)

    participants: Mapped[list["PresentationParticipant"]] = relationship(
        back_populates="session", cascade="all, delete-orphan"
    )

    __table_args__ = (
        Index("ix_presentation_sessions_state", "pres_state", "ai_state"),
    )


class PresentationParticipant(Base):
    __tablename__ = "presentation_participants"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    session_id: Mapped[str] = mapped_column(
        ForeignKey("presentation_sessions.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"), nullable=True, index=True
    )
    display_name: Mapped[str] = mapped_column(String(128), nullable=False, default="Guest")
    role: Mapped[str] = mapped_column(String(20), nullable=False, default="attendee")
    # Hash of the guest join token; revocation = presence check at join time.
    guest_token_hash: Mapped[str | None] = mapped_column(String(128), nullable=True)
    joined_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow)
    left_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    reconnected_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)

    session: Mapped["PresentationSession"] = relationship(back_populates="participants")

    __table_args__ = (
        UniqueConstraint("session_id", "user_id", name="uq_participant_session_user"),
        Index("ix_participants_session", "session_id"),
    )


# ---------------------------------------------------------------------------
# Moderation: audience questions
# ---------------------------------------------------------------------------

QUESTION_STATUSES = ("raised", "approved", "deferred", "rejected", "answered", "unanswered")


class PresentationQuestion(Base):
    __tablename__ = "presentation_questions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True)
    session_id: Mapped[str] = mapped_column(
        ForeignKey("presentation_sessions.id", ondelete="CASCADE"), nullable=False
    )
    participant_id: Mapped[int] = mapped_column(
        ForeignKey("presentation_participants.id"), nullable=False
    )
    source: Mapped[str] = mapped_column(String(10), nullable=False, default="text")
    text: Mapped[str] = mapped_column(Text, nullable=False)
    # Voice questions reference the existing system-audio recordings storage.
    audio_recording_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="raised", index=True)
    ai_answered: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    answer_text: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Duplicate prevention: same participant raising the same question inside
    # the rate window is rejected at the service layer; the key also guards
    # against transport-level double submissions.
    idempotency_key: Mapped[str | None] = mapped_column(String(64), nullable=True)
    decided_by: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"), nullable=True
    )
    decided_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=_utcnow, index=True)

    __table_args__ = (
        Index("ix_questions_session_status", "session_id", "status"),
        UniqueConstraint(
            "session_id", "participant_id", "idempotency_key",
            name="uq_question_idempotency",
        ),
    )


